#!/usr/bin/env python3
"""Pack ui/m_doom_c64.png as the menu logo.

The PNG is 128×64 hires, 2px = 1 multicolour pixel (64×64). Ink is 60 rows;
those are scaled into 7 mode-E rows (56 lines) so the control page still fits
under the logo. Each scanline gets its own 4 GTIA colours (black plus three).
"""
from __future__ import annotations

from collections import Counter
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
PNG = ROOT / "ui" / "m_doom_c64.png"
OUT = ROOT / "src" / "menu_title.asm"
PREVIEW = ROOT / "ui" / "doomlogo_preview.png"

ROWS = 7
OUT_H = ROWS * 8
SRC_INK = 60
COLS = 16
LEFT = (40 - COLS) // 2
PIX = COLS * 4

PEPTO = (
	(0x00, 0x00, 0x00),
	(0xFF, 0xFF, 0xFF),
	(0x68, 0x37, 0x2B),
	(0x70, 0xA4, 0xB2),
	(0x6F, 0x3D, 0x86),
	(0x58, 0x8D, 0x43),
	(0x35, 0x28, 0x79),
	(0xB8, 0xC7, 0x6F),
	(0x6F, 0x4F, 0x25),
	(0x43, 0x39, 0x00),
	(0x9A, 0x67, 0x59),
	(0x44, 0x44, 0x44),
	(0x6C, 0x6C, 0x6C),
	(0x9A, 0xD2, 0x84),
	(0x6C, 0x5E, 0xB5),
	(0x95, 0x95, 0x95),
)
# Same map as a8_c64pal in a8menuhw.asm. Runtime runs these through a8_to_pal.
GTIA = (
	0x00, 0x0E, 0x42, 0xA6, 0x64, 0xC4, 0x84, 0x1C,
	0x26, 0x24, 0x4A, 0x06, 0x08, 0xCA, 0x9A, 0x0C,
)


def nearest(rgb: tuple[int, int, int]) -> int:
	best = 0
	best_d = 10**9
	for i, (cr, cg, cb) in enumerate(PEPTO):
		d = (rgb[0] - cr) ** 2 + (rgb[1] - cg) ** 2 + (rgb[2] - cb) ** 2
		if d < best_d:
			best_d = d
			best = i
	return best


def dist(a: int, b: int) -> int:
	ar, ag, ab = PEPTO[a]
	br, bg, bb = PEPTO[b]
	return (ar - br) ** 2 + (ag - bg) ** 2 + (ab - bb) ** 2


def src_y(oy: int) -> int:
	return min(SRC_INK - 1, int(oy * (SRC_INK - 1) / (OUT_H - 1) + 0.5))


def pick_palette(idxs: list[int]) -> list[int]:
	counts = Counter(c for c in idxs if c != 0)
	chosen = [0]
	pool = list(counts.items())
	while len(chosen) < 4 and pool:
		best_i = 0
		best_s = -1
		for i, (col, n) in enumerate(pool):
			if col in chosen:
				continue
			score = n * min(dist(col, c) for c in chosen)
			if score > best_s:
				best_s = score
				best_i = i
		col = pool.pop(best_i)[0]
		if col not in chosen:
			chosen.append(col)
	while len(chosen) < 4:
		chosen.append(0)
	return chosen


def closest(idx: int, palette: list[int]) -> int:
	if idx in palette:
		return palette.index(idx)
	best = 0
	best_d = 10**9
	for slot, col in enumerate(palette):
		d = dist(idx, col)
		if d < best_d:
			best_d = d
			best = slot
	return best


def fmt(data: list[int], per: int = 16) -> list[str]:
	lines = []
	for i in range(0, len(data), per):
		chunk = data[i : i + per]
		lines.append("\t!byte " + ",".join(f"${b:02x}" for b in chunk))
	return lines


def main() -> None:
	im = Image.open(PNG).convert("RGB")
	if im.size != (128, 64):
		raise SystemExit(f"{PNG.name}: expected 128x64, got {im.size}")
	px = im.load()

	# Per scanline: 64 C64 colour indices, then a 4-colour palette.
	lines_idx: list[list[int]] = []
	palettes: list[list[int]] = []
	for oy in range(OUT_H):
		sy = src_y(oy)
		idxs = [nearest(px[x * 2, sy]) for x in range(PIX)]
		lines_idx.append(idxs)
		palettes.append(pick_palette(idxs))

	cells: list[int] = []
	for cy in range(ROWS):
		for cx in range(COLS):
			for s in range(8):
				oy = cy * 8 + s
				pal = palettes[oy]
				byte = 0
				for p in range(4):
					idx = lines_idx[oy][cx * 4 + p]
					byte |= closest(idx, pal) << (6 - 2 * p)
				cells.append(byte)

	pf0, pf1, pf2, bk = [], [], [], []
	for pal in palettes:
		bk.append(GTIA[pal[0]])
		pf0.append(GTIA[pal[1]])
		pf1.append(GTIA[pal[2]])
		pf2.append(GTIA[pal[3]])

	out = [
		f"; Auto-generated by tools/gen_menu_title.py from {PNG.name}",
		"; 64x56 mode-E logo. title_src_* is one GTIA byte per scanline (NTSC).",
		"TITLE_SPR_COUNT\t= 0",
		f"MENU_TITLE_LEFT\t= {LEFT}",
		f"MENU_TITLE_COLS\t= {COLS}",
		f"MENU_TITLE_ROWS\t= {ROWS}",
		"MENU_TITLE_PAD_Y\t= 0",
		"",
		"title_spr_xmsb\t!byte $00",
		"title_spr_x\t!byte $00",
		"",
		"title_src_pf0",
	]
	out.extend(fmt(pf0))
	out.append("title_src_pf1")
	out.extend(fmt(pf1))
	out.append("title_src_pf2")
	out.extend(fmt(pf2))
	out.append("title_src_bk")
	out.extend(fmt(bk))
	out.append("")
	out.append("menu_title_data")
	out.extend(fmt(cells))
	out.append("")
	out.append("menu_title_spr")
	out.append("")
	OUT.write_text("\n".join(out) + "\n", encoding="utf-8")

	prev = Image.new("RGB", (160, OUT_H), (0, 0, 0))
	pp = prev.load()
	for oy in range(OUT_H):
		pal = palettes[oy]
		for x in range(PIX):
			slot = closest(lines_idx[oy][x], pal)
			pp[LEFT * 4 + x, oy] = PEPTO[pal[slot]]
	big = prev.resize((160 * 3, OUT_H * 3), Image.Resampling.NEAREST)
	big.save(PREVIEW)
	print(f"wrote {OUT.relative_to(ROOT)} rows={ROWS} + {PREVIEW.relative_to(ROOT)}")


if __name__ == "__main__":
	main()
