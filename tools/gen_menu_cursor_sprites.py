#!/usr/bin/env python3
"""Pack the SquareDoom skull into two 24×21 frames of four luminance layers.

ui/m_skull_c64.png is the closed skull. ui/m_skull2_c64.png opens the eyes
(red sockets, white glints). The Atari cursor only has one hue plus a white
glyph, so red and white eye pixels are both the brightest layer: the eyes
blink on. Bone shades are the three darker layers. build-a8.bat runs this,
then tools/gen_a8_cursor.py.
"""
from __future__ import annotations

from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
BASE = ROOT / "ui" / "m_skull_c64.png"
EYES = ROOT / "ui" / "m_skull2_c64.png"
OUT = ROOT / "src" / "menu_cursor_spr.asm"

SPR_W = 24
SPR_H = 21
# Front to back. gen_a8_cursor.py reads them as lums 14, 12, 8, 0.
LUMS = (14, 12, 8, 0)

PEPTO = (
	(0x00, 0x00, 0x00),
	(0xFF, 0xFF, 0xFF),
	(0x68, 0x37, 0x2B),
	(0x70, 0xA4, 0xB2),
	(0x6F, 0x3D, 0x86),
	(0x58, 0x8D, 0x43),
	(0x35, 0x28, 0x79),
	(0xB8, 0xC7, 0x6F),
	(0x6F, 0x4F, 0x25),
	(0x43, 0x39, 0x00),
	(0x9A, 0x67, 0x59),
	(0x44, 0x44, 0x44),
	(0x6C, 0x6C, 0x6C),
	(0x9A, 0xD2, 0x84),
	(0x6C, 0x5E, 0xB5),
	(0x95, 0x95, 0x95),
)
# Pepto index → luminance. Red and white share the front layer (the blink).
TO_LUM = {
	1: 14,
	2: 14,
	7: 14,
	10: 12,
	8: 8,
	9: 0,
}


def nearest(rgb: tuple[int, int, int]) -> int:
	best = 0
	best_d = 10**9
	for i, (cr, cg, cb) in enumerate(PEPTO):
		d = (rgb[0] - cr) ** 2 + (rgb[1] - cg) ** 2 + (rgb[2] - cb) ** 2
		if d < best_d:
			best_d = d
			best = i
	return best


def frame_lums(path: Path) -> list[list[int | None]]:
	im = Image.open(path).convert("RGBA")
	w, h = im.size
	px = im.load()
	grid: list[list[int | None]] = [[None] * SPR_W for _ in range(SPR_H)]
	for y in range(min(h, SPR_H)):
		for x in range(min(w, SPR_W)):
			r, g, b, a = px[x, y]
			if a < 16:
				continue
			lum = TO_LUM.get(nearest((r, g, b)))
			if lum is None:
				raise SystemExit(f"{path.name}: unmapped colour {(r, g, b)} at {x},{y}")
			grid[y][x] = lum
	return grid


def pack_layer(grid: list[list[int | None]], lum: int) -> list[int]:
	raw = []
	for y in range(SPR_H):
		for col in range(3):
			byte = 0
			for bit in range(8):
				if grid[y][col * 8 + bit] == lum:
					byte |= 0x80 >> bit
			raw.append(byte)
	raw.append(0)
	return raw


def fmt(data: list[int], per: int = 16) -> list[str]:
	lines = []
	for i in range(0, len(data), per):
		chunk = data[i : i + per]
		lines.append("\t!byte " + ",".join(f"${b:02x}" for b in chunk))
	return lines


def main() -> None:
	frames = [frame_lums(BASE), frame_lums(EYES)]
	blob: list[int] = []
	for grid in frames:
		for lum in LUMS:
			blob.extend(pack_layer(grid, lum))
	lines = [
		"; Auto-generated by tools/gen_menu_cursor_sprites.py",
		"; Frame 0 closed, frame 1 eyes. Layers front to back: 14, 12, 8, 0.",
		"CURSOR_SPR_COUNT\t= 4",
		"CURSOR_FRAMES\t= 2",
		"CURSOR_SPR_W\t= 24",
		"",
		"menu_cursor_spr",
	]
	lines.extend(fmt(blob))
	lines.append("")
	OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
	print(f"wrote {OUT.relative_to(ROOT)} bytes={len(blob)}")


if __name__ == "__main__":
	main()
