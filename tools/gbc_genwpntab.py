#!/usr/bin/env python3
"""Weapon timing tables for the GBC: editor/doom64.json "gbWeapons" -> <outdir>/wpntable.asm.

Edited in the editor's Weapons tab (period, overhang, pose steps; times in VBlanks). Writes:
  DEF WPN_PERIOD_<NAME> / WPN_ANIM_<NAME>   used by WpnDef in gbc/wpn.asm (the anim length of a table
                                            weapon is the sum of its step durations)
  Pose<Name> tables + WpnPoseTab            gbc/wpn.asm WpnPose: db overhang, (until, dy, frame)..., 0   (until = running sum of the editor's durations)
                                            frame 0 = idle (dy + overhang + bob), 1 = alt (dy absolute)
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DOC = os.path.join(os.path.dirname(HERE), "editor", "doom64.json")

# (json id, asm name, has a pose table) in WPN_* id order; chaingun / chainsaw: period + anim only.
WEAPONS = [
    ("fist", "FIST", True),
    ("shotgun", "SHOT", True),
    ("chaingun", "CHAIN", False),
    ("rocket", "ROCKET", True),
    ("pistol", "PISTOL", True),
    ("chainsaw", "SAW", False),
]
MAX_STEPS = 8


def check(cond, wid, msg):
    if not cond:
        raise SystemExit("gbc_genwpntab: %s: %s" % (wid, msg))


def main():
    outdir = sys.argv[1]
    os.makedirs(outdir, exist_ok=True)
    with open(DOC, encoding="utf-8") as f:
        lst = json.load(f).get("gbWeapons")
    if not isinstance(lst, list):
        raise SystemExit("gbc_genwpntab: no gbWeapons in %s (open the editor's Weapons tab and save)" % DOC)
    by_id = {w.get("id"): w for w in lst}
    consts = ["; Generated by tools/gbc_genwpntab.py from editor/doom64.json (Weapons tab) - do not edit."]
    pose = []
    pointers = []
    summary = []
    for wid, name, tabled in WEAPONS:
        w = by_id.get(wid)
        check(w is not None, wid, "missing from gbWeapons")
        period = int(w["period"])
        check(1 <= period <= 255, wid, "period %d not in 1..255" % period)
        if tabled:
            steps = w.get("steps", [])
            check(len(steps) <= MAX_STEPS, wid, "more than %d steps" % MAX_STEPS)
            overhang = int(w.get("overhang", 0))
            check(0 <= overhang <= 64, wid, "overhang %d not in 0..64" % overhang)
            prev = 0
            pose.append("Pose%s:" % name.capitalize())
            pose.append("    db %d" % overhang)
            for i, st in enumerate(steps):
                if "duration" in st:
                    dur = int(st["duration"])
                else:                       # older file: end time
                    dur = int(st["until"]) - prev
                dy = int(st["dy"])
                check(dur >= 1, wid, "step %d: duration %d must be >= 1" % (i + 1, dur))
                until = prev + dur          # the editor stores durations; the table holds end times
                check(until <= 255, wid, "step %d ends at %d VBlanks; the table holds at most 255" % (i + 1, until))
                check(-128 <= dy <= 127, wid, "step %d: dy %d not in -128..127" % (i + 1, dy))
                check(st.get("frame") in ("idle", "alt"), wid, "step %d: frame must be idle or alt" % (i + 1))
                pose.append("    db %d, %d, %d" % (until, dy, 1 if st["frame"] == "alt" else 0))
                prev = until
            pose.append("    db 0")
            anim = prev
            pointers.append("Pose" + name.capitalize())
        else:
            anim = int(w["anim"])
            check(0 <= anim <= 255, wid, "anim %d not in 0..255" % anim)
            pointers.append("0")
        consts.append("DEF WPN_PERIOD_%s EQU %d" % (name, period))
        consts.append("DEF WPN_ANIM_%s EQU %d" % (name, anim))
        summary.append("%s %d/%d" % (wid, period, anim))
    out = consts + [
        'SECTION "wpntable", ROM0',
        "; Per weapon id (WPN_*): pose table or 0 (chaingun, chainsaw).",
        "WpnPoseTab:",
        "    dw " + ", ".join(pointers),
    ] + pose
    open(os.path.join(outdir, "wpntable.asm"), "w", newline="\n").write("\n".join(out) + "\n")
    print("weapon table (period/anim VBlanks): " + ", ".join(summary))


if __name__ == "__main__":
    main()
