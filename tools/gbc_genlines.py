#!/usr/bin/env python3
"""GBC line plotter generator + bit-exact reference.

Writes (RGBDS includes):
  <outdir>/line_bodies.inc   unrolled Bresenham bodies + LineTable
  <outdir>/test_lines.inc    TestLines (x0,y0,x1,y1)*, $FF terminator

Framebuffer: 16 columns x 224 B (column-major tiles). Pixel (x,y):
  ptr = FB + (x >> 3) * 224 + y * 2 (plane 0), bit = 7 - (x & 7). Column step = COLSTEP macro.
Bodies draw colour 1 (plane 0 only) with `set n,[hl]`.
Registers: A err, B major delta M, C minor delta m, D pixel count, E spare, HL pointer.
Kinds: 0 X-major down, 1 X-major up, 2 Y-major down, 3 Y-major up. x0 <= x1.
"""
import os
import sys

VIEW_W = 128
VIEW_H = 112


def gen_bodies():
    out = ["; Generated by tools/gbc_genlines.py - do not edit.", "LineBodies:"]
    for major, down in (("x", True), ("x", False), ("y", True), ("y", False)):
        pfx = "%s%s" % (major, "d" if down else "u")
        step = "inc hl" if down else "dec hl"    # columns are not page aligned: 16-bit steps
        for k in range(8):
            lbl = "%s_%d" % (pfx, k)
            out.append("%s:" % lbl)
            out.append("    set %d, [hl]" % (7 - k))
            out.append("    dec d")
            out.append("    ret z")
            if major == "x":
                out += ["    sub c", "    jr nc, %s_n" % lbl,
                        "    add a, b", "    " + step, "    " + step]
                out.append("%s_n:" % lbl)
                if k == 7:
                    out += ["    COLSTEP", "    jr %s_0" % pfx]
            else:
                out += ["    " + step, "    " + step, "    sub c",
                        "    jr nc, %s" % lbl, "    add a, b"]
                if k == 7:
                    out += ["    COLSTEP", "    jr %s_0" % pfx]
    out.append("LineTable:")
    for pfx in ("xd", "xu", "yd", "yu"):
        out.append("    dw " + ", ".join("%s_%d" % (pfx, k) for k in range(8)))
    return "\n".join(out) + "\n"


def test_lines():
    cx, cy = 64, 56
    pts = []
    for x in range(0, VIEW_W, 8):
        pts += [(x, 0), (x, VIEW_H - 1)]
    for y in range(0, VIEW_H, 8):
        pts += [(0, y), (VIEW_W - 1, y)]
    lines = [(cx, cy, x, y) for (x, y) in pts]
    # Edge/degenerate cases: point, horizontal, vertical, 45 degrees, steep, shallow.
    lines += [(10, 10, 10, 10), (5, 100, 120, 100), (100, 5, 100, 105),
              (20, 20, 60, 60), (60, 20, 20, 60), (3, 3, 9, 100), (110, 109, 20, 106),
              (127, 0, 127, 111), (0, 111, 127, 111), (0, 0, 0, 111)]
    return lines


def ref_line(fb, x0, y0, x1, y1):
    """Same algorithm as the SM83 bodies. fb is a set of (x, y)."""
    if x1 < x0:
        x0, y0, x1, y1 = x1, y1, x0, y0
    dx = x1 - x0
    dy = abs(y1 - y0)
    ystep = 1 if y1 >= y0 else -1
    if dx >= dy:
        M, m, xmaj = dx, dy, True
    else:
        M, m, xmaj = dy, dx, False
    err = M >> 1
    count = M + 1
    x, y = x0, y0
    while True:
        fb.add((x, y))
        count -= 1
        if count == 0:
            break
        if xmaj:
            err -= m
            if err < 0:
                err += M
                y += ystep
            x += 1
        else:
            y += ystep
            err -= m
            if err < 0:
                err += M
                x += 1


def reference_frame():
    fb = set()
    for l in test_lines():
        ref_line(fb, *l)
    return fb


def main():
    outdir = sys.argv[1]
    os.makedirs(outdir, exist_ok=True)
    with open(os.path.join(outdir, "line_bodies.inc"), "w", newline="\n") as f:
        f.write(gen_bodies())
    with open(os.path.join(outdir, "test_lines.inc"), "w", newline="\n") as f:
        f.write("; Generated by tools/gbc_genlines.py - do not edit.\nTestLines:\n")
        for l in test_lines():
            f.write("    db %d, %d, %d, %d\n" % l)
        f.write("    db $FF\n")


if __name__ == "__main__":
    main()
