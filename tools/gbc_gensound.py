#!/usr/bin/env python3
"""Sound data for the GBC build, from the A8 sources.

Writes <outdir>/sndids.inc (SND_* equates) and <outdir>/sound.inc (data):
  SND_<NAME> ids (the A8 SOUND_* order from tools/gensounds.py EFFECTS), SndTable (one word per id)
  and one block per effect: N, voice (0 player / 1 enemy / 2 world), priority, N PC-speaker bytes
  (the Wolf inverse-frequency byte the A8 bakes into POKEY AUDF, 0 = silence). gbc/sound.asm turns the
  byte into a pulse period with the same pitch (1193181 / (byte * 60) Hz).
  Per-type cue tables indexed by ENT_* (sight / wince / death from ENEMY_CUES; the attack clip's
  sound frame and id from editor/enemies/*.json), SndWpn (src/weapon.asm wpn_sound) and SndPick
  (src/world.asm gb_snd -> pickup_sound: PS_AMMO plays WPNUP, the rest ITEMUP).
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))
import gbc_a8const as a8  # noqa: E402
from gensounds import EFFECTS, ENEMY_CUES  # noqa: E402
from pcsrc import resolve  # noqa: E402

NONE = 255
# ENT_* (a8const) -> editor enemy file and ENEMY_CUES name
TYPES = [("ENT_POSS", "poss", "Possessed"), ("ENT_BARON", "baron", "Baron"),
         ("ENT_PINKY", "pinky", "Pinky"), ("ENT_IMP", "imp", "Imp")]
HDR = "; Generated by tools/gbc_gensound.py from the A8 sound sources - do not edit."


def table_bytes(src, label):
    """The !byte list under `label` in an A8 source, as tokens."""
    lines = src.split("\n")
    i = next(k for k, l in enumerate(lines) if l.strip() == label)
    toks = []
    k = i + 1
    while k < len(lines) and lines[k].strip().startswith("!byte"):
        toks += [t.strip() for t in lines[k].split("!byte", 1)[1].split(";")[0].split(",")]
        k += 1
    return toks


POKEY_64K = 63921.0
GB_PULSE_VOL = 12                      # pulse channels play at 12 / 15 (gbc/sound.asm SND_VOL_PULSE)


def nr43(audf):
    """POKEY AUDF -> GB NR43 (15-bit LFSR, width 0): LFSR clock 262144 / (r * 2^s), r 0 = 0.5, nearest to the
    POKEY poly clock 63921 / (AUDF + 1)."""
    want = POKEY_64K / (audf + 1)
    best = None
    for sh in range(16):
        for r in range(8):
            hz = 262144.0 / ((r or 0.5) * (1 << sh))
            err = abs(hz - want) / want
            if best is None or err < best[0]:
                best = (err, sh, r)
    return (best[1] << 4) | best[2]


def gbvol(v):
    """A8 volume 0..15 -> GB 0..15 scaled like the pulse channels (12 / 15), at least 1 if audible."""
    return max(1, round(v * GB_PULSE_VOL / 15)) if v else 0


def main():
    outdir = sys.argv[1]
    os.makedirs(outdir, exist_ok=True)
    defs = a8.read_defs()
    ids = {name: i for i, (name, _l, _v, _p) in enumerate(EFFECTS)}
    ent = {t: a8.evaluate(t, defs) for t, _f, _c in TYPES}

    equ = [HDR]
    for name, i in ids.items():
        equ.append("DEF SND_%s EQU %d" % (name, i))
    equ.append("DEF SND_COUNT EQU %d" % len(EFFECTS))
    equ.append("DEF SND_NONE EQU %d" % NONE)

    out = [HDR, 'SECTION "sounddata", ROM0', "IF !DEF(TEST_EXIT)", "SndTable:"]
    blocks = {}
    order = []
    labels = []
    for _name, lump, voice, prio in EFFECTS:
        freq = resolve(lump)
        body = [len(freq), voice & 3, prio & 255] + freq
        key = tuple(body)
        if key not in blocks:
            blocks[key] = "SndFx%d" % len(order)
            order.append((blocks[key], body))
        labels.append(blocks[key])
    for lab in labels:
        out.append("    dw %s" % lab)
    for lab, body in order:
        out.append("%s:" % lab)
        for k in range(0, len(body), 16):
            out.append("    db " + ", ".join(str(b) for b in body[k:k + 16]))

    out.append("ENDC")      # test builds (ROM0 nearly full) carry no sound data: gbc/sound.asm stubs

    # Per-type cue tables, indexed by ENT_* (the four types are ENT 0..3).
    sight, wince, death, atk_f, atk_id = ([NONE] * 4 for _ in range(5))
    for t, stem, cname in TYPES:
        e = ent[t]
        cues = ENEMY_CUES[cname]
        sight[e] = ids[cues["sight"]]
        wince[e] = ids[cues["wince"]]
        death[e] = ids[cues["death"]]
        doc = json.load(open(os.path.join(ROOT, "editor", "enemies", stem + ".json"), encoding="utf-8"))
        for c in doc["clips"]:
            kind = (c.get("sound") or "").lower()
            if kind in ("melee", "shoot") and c.get("name") in doc.get("exportClips", []):
                atk_f[e] = max(0, min(int(c.get("soundFrame") or 0), int(c["len"]) - 1))
                atk_id[e] = ids[cues[kind]]
    for label, vals in (("SndSight", sight), ("SndWince", wince), ("SndDeath", death),
                        ("SndAtkFrame", atk_f), ("SndAtkId", atk_id)):
        out.append("%s:: db %s" % (label, ", ".join(str(v) for v in vals)))

    wsrc = open(os.path.join(ROOT, "src", "weapon.asm"), encoding="utf-8").read()
    mute = (a8.evaluate("WPN_FIST", defs), a8.evaluate("WPN_SAW", defs))
    wpn = []
    for k, t in enumerate(table_bytes(wsrc, "wpn_sound")):
        m = re.fullmatch(r"SOUND_(\w+)", t)
        # fist / chainsaw: the A8 never calls play_sound from fire_shot for them (their sound is the hit)
        wpn.append(ids[m.group(1)] if m and k not in mute else NONE)
    out.append("SndWpn:: db %s" % ", ".join(str(v) for v in wpn))

    world = open(os.path.join(ROOT, "src", "world.asm"), encoding="utf-8").read()
    ps = {m.group(1): int(m.group(2)) for m in re.finditer(r"^(PS_\w+)\s*=\s*(\d+)", world, re.M)}
    pick = [ids["WPNUP"] if ps[t] == ps["PS_AMMO"] else ids["ITEMUP"] for t in table_bytes(world, "gb_snd")]
    out.append("SndPick:: db %s" % ", ".join(str(v) for v in pick))
    equ.append("DEF SND_PICK_N EQU %d" % len(pick))

    # CH4 noise (A8 a8_noise elevator rumble, a8_saw chainsaw): POKEY AUDF -> NR43, A8 volume -> GB volume.
    irq = open(os.path.join(ROOT, "src", "a8irq.asm"), encoding="utf-8").read()
    elev_f = int(re.search(r"a8_noise\n.*?lda #\$([0-9a-f]+)\n\s*sta \$d204", irq, re.S).group(1), 16)
    sv = {n: a8.evaluate(n, defs) for n in ("SAW_IDLE_F", "SAW_FIRE_F", "SAW_BITE_MASK", "SAW_BITE_LO", "SAW_RNG_TAP")}
    equ.append("DEF NZ_ELEV EQU %d" % nr43(elev_f))
    equ.append("DEF NZ_IDLE EQU %d" % nr43(sv["SAW_IDLE_F"]))
    equ.append("DEF NZ_FIRE EQU %d" % nr43(sv["SAW_FIRE_F"]))
    equ.append("DEF NZ_BITE_MASK EQU %d" % sv["SAW_BITE_MASK"])
    equ.append("DEF NZ_RNG_TAP EQU %d" % sv["SAW_RNG_TAP"])
    # effects_vol $0F: elevator and bite full, idle >> 3, fire >> 2 (a8_saw)
    for name, v in (("ELEV", 15), ("BITE", 15), ("IDLE", 15 >> 3), ("FIRE", 15 >> 2)):
        equ.append("DEF NZ_V_%s EQU %d" % (name, gbvol(v)))
    out.append("IF !DEF(TEST_EXIT)")
    out.append("SndBiteTab:: db %s" % ", ".join(str(nr43(sv["SAW_BITE_LO"] + k))
                                                for k in range(sv["SAW_BITE_MASK"] + 1)))
    out.append("ENDC")

    with open(os.path.join(outdir, "sndids.inc"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(equ) + "\n")
    with open(os.path.join(outdir, "sound.inc"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print("sound.inc: %d effects, %d blocks, %d data bytes" % (len(EFFECTS), len(order),
                                                              sum(len(b) for _l, b in order)))


if __name__ == "__main__":
    main()
