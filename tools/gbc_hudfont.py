#!/usr/bin/env python3
"""HUD font and A8 colour table for the GBC build, from the A8 / editor sources.

Writes <outdir>/hudfont.inc:
  HudFontTiles: 96 CGB tiles (16 bytes each) for ASCII 32..127, from ui/doomfont.png (the A8 UI
  charset, tools/genuifont.py). Glyph pixels are colour 1 (bitplane 0). HUD tile id = ASCII - 32;
  the tiles live at $9000 in VRAM bank 0 and the HUD rows are drawn in $8800 (signed) tile mode.
  The A8 icons come with the sheet: '[' '\\' ']' key cards (red, yellow, blue), '{' '|' '}' bullet,
  shell, rocket. '^' (health) and '~' (armour) are reserved for the GBC HUD; while their sheet
  cells are empty a placeholder (cross, shield) is used - draw the real glyphs into the sheet.
  A8Pal: dw BGR555 per A8 colour byte >> 1 (128 entries), from editor/js/model.js A8_HEX (the
  editor's NTSC GTIA approximation).
"""
import os
import re
import sys

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PNG = os.path.join(ROOT, "ui", "doomfont.png")
MODEL_JS = os.path.join(ROOT, "editor", "js", "model.js")
COLS, ROWS, CELL, ASCII_BASE = 8, 12, 8, 32          # same sheet layout as tools/genuifont.py

HEALTH_CH, ARMOUR_CH = 0x5E, 0x7E                     # '^', '~'
PLACEHOLDER = {
    HEALTH_CH: ["00000000", "00011000", "00011000", "01111110", "01111110", "00011000", "00011000", "00000000"],
    ARMOUR_CH: ["00000000", "01111110", "01111110", "01111110", "00111100", "00111100", "00011000", "00000000"],
}


def glyph_rows(im, code):
    i = code - ASCII_BASE
    row, col = divmod(i, COLS)
    out = []
    for y in range(CELL):
        b = 0
        for x in range(CELL):
            if im.getpixel((col * CELL + x, row * CELL + y)) > 128:
                b |= 0x80 >> x
        out.append(b)
    return out


def a8_hex_table():
    src = open(MODEL_JS, encoding="utf-8").read()
    m = re.search(r"export const A8_HEX = \[(.*?)\];", src, re.S)
    if not m:
        raise SystemExit("gbc_hudfont: A8_HEX not found in %s" % MODEL_JS)
    cols = re.findall(r'"#([0-9a-fA-F]{6})"', m.group(1))
    if len(cols) != 128:
        raise SystemExit("gbc_hudfont: A8_HEX has %d entries, expected 128" % len(cols))
    out = []
    for h in cols:
        r, g, b = int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16)
        out.append((r >> 3) | ((g >> 3) << 5) | ((b >> 3) << 10))
    return out


def main():
    outdir = sys.argv[1]
    os.makedirs(outdir, exist_ok=True)
    im = Image.open(PNG).convert("L")
    if im.size != (COLS * CELL, ROWS * CELL):
        raise SystemExit("gbc_hudfont: %s is %dx%d" % (PNG, im.width, im.height))
    out = ["; Generated by tools/gbc_hudfont.py from ui/doomfont.png and editor/js/model.js - do not edit.",
           "HudFontTiles::"]
    placeholders = []
    for code in range(ASCII_BASE, ASCII_BASE + COLS * ROWS):
        rows = glyph_rows(im, code)
        if code in PLACEHOLDER and not any(rows):
            rows = [int(r, 2) for r in PLACEHOLDER[code]]
            placeholders.append(chr(code))
        data = []
        for r in rows:
            data += [r, 0]
        out.append("    db " + ",".join("$%02X" % b for b in data) + "   ; %r" % chr(code))
    out.append("HudFontTilesEnd::")
    out.append("A8Pal::   ; BGR555 per A8 colour byte >> 1")
    pal = a8_hex_table()
    for k in range(0, 128, 8):
        out.append("    dw " + ",".join("$%04X" % c for c in pal[k:k + 8]))
    open(os.path.join(outdir, "hudfont.inc"), "w", newline="\n").write("\n".join(out) + "\n")
    print("hud font: 96 glyphs%s, A8 palette 128 colours" %
          (" (placeholder %s)" % " ".join(placeholders) if placeholders else ""))


if __name__ == "__main__":
    main()
