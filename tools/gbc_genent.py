#!/usr/bin/env python3
"""Entity mesh data for the GBC build: items / door meshes and enemy frames, in ROM bank ENT_BANK.

Writes <outdir>/ents.inc:
  ROM0: ItemTab (dw per item mesh), EnemyTab (dw per enemy type), EntBank (db)
  bank ENT_BANK:
    item mesh : db nv, ne, shift, radius ; verts (x,y,z)*nv ; edges (a,b)*ne
    enemy     : db nv, ne, shift, radius, nframes, hp, block_r, weapon_vert
                db (start,len) * 5   stand, walk, attack, pain, death
                edges (a,b)*ne ; frames: nv*3 bytes each
Item order = thing types 0..18 then the four door meshes (see ITEM_ORDER).
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import gbc_entity as ge  # noqa: E402

ENT_BANK = 10

# thing type (TH_*) 0..18, then door types 0..3
ITEM_ORDER = ["small health", "large health", "security armor", "combat armor", "ammo box", "shells",
              "box of rockets", "shotgun", "chaingun", "chainsaw", "rocket launcher", "backpack",
              "red keycard", "yellow keycard", "blue keycard", "soulsphere", "radsuit",
              "lightpost", "barrel", "Tech", "Arch", "Tri", "Crack", "fireball"]

ATTACK_CLIP = {"poss": "missile", "baron": "attack", "pinky": "melee", "imp": "attack"}


def db(vals, per=16):
    return "\n".join("    db " + ",".join(str(v & 255) for v in vals[i:i + per]) for i in range(0, len(vals), per))


def flat(pairs):
    return [v for p in pairs for v in p]


def main():
    outdir = sys.argv[1]
    os.makedirs(outdir, exist_ok=True)
    items = ge.load_items()
    enemies = ge.load_enemies()
    out = ["; Generated by tools/gbc_genent.py - do not edit.",
           'SECTION "ents", ROMX, BANK[%d]' % ENT_BANK]
    for i, name in enumerate(ITEM_ORDER):
        m = items[name]
        out.append("Item%d:   ; %s" % (i, name))
        out.append("    db %d, %d, %d, %d" % (len(m.verts), len(m.edges), m.shift, m.radius))
        out.append(db(flat(m.verts)))
        out.append(db(flat(m.edges)))
    for ti, (key, _) in enumerate(ge.ENEMY_FILES):
        e = enemies[key]
        nv = len(e["frames"][0])
        out.append("Enemy%d:   ; %s" % (ti, key))
        out.append("    db %d, %d, 4, 3, %d, %d, %d, %d" % (nv, len(e["edges"]), len(e["frames"]),
                                                              min(e["hp"], 255), e["block_r"], e["weapon_vert"]))
        clips = []
        for cname in ("stand", "walk", ATTACK_CLIP[key], "pain", "death"):
            s, n = e["clips"][cname]
            clips += [s, n]
        out.append(db(clips))
        out.append(db(flat(e["edges"])))
        for f in e["frames"]:
            out.append(db(flat(f)))
    # Enemy muzzle LODs come from the editor's GB Sprites tab (doom64.json gbSprites enemy_muzzle_0..2),
    # stamped at their own size, centred on the weapon vertex. The splat is still the A8 PNG, 24x21.
    # Layout per image: db width_bytes, height, origin_x, origin_y (px from the box's top left to the tip),
    # then width_bytes columns of height bytes (bit 7 = left), as gbc/objects.asm StampImage reads it.
    from PIL import Image
    import json
    with open(os.path.join(ge.ROOT, "editor", "doom64.json"), encoding="utf-8") as f:
        gbs = {sp["id"]: sp for sp in json.load(f).get("gbSprites", [])}
    for tag, label, path in (("Emuz", "EmuzPtr", "enemy_muzzle_%d"), ("Splat", "SplatPtr", "weapons/splat_%d.png")):
        out.append("%s:: dw " % label + ", ".join("%s%d" % (tag, i) for i in range(3)))
        for i in range(3):
            if tag == "Emuz":
                sp = gbs.get(path % i)
                if sp is None:
                    raise SystemExit("gbc_genent: sprite %r missing from doom64.json (gbSprites)" % (path % i))
                w, h = sp["w"], sp["h"]
                if w > 128 or h > 112:
                    raise SystemExit("gbc_genent: %s is %dx%d, larger than the viewport" % (path % i, w, h))
                oxy = (w // 2, h // 2)

                def ink(x, y, sp=sp):
                    return sp["rows"][y][x] == "#"
            else:
                im = Image.open(os.path.join(ge.ROOT, "assets", path % i)).convert("L")
                if im.size != (24, 21):
                    raise SystemExit("%s is %dx%d, expected 24x21" % ((path % i,) + im.size))
                w, h = 24, 21
                oxy = (12, 10)

                def ink(x, y, im=im):
                    return im.getpixel((x, y)) > 128
            wb = (w + 7) // 8
            rows = [wb, h, oxy[0], oxy[1]]
            for b in range(wb):
                for y in range(h):
                    v = 0
                    for x in range(8):
                        if b * 8 + x < w and ink(b * 8 + x, y):
                            v |= 0x80 >> x
                    rows.append(v)
            out.append("%s%d:" % (tag, i))
            out.append(db(rows))
    out.append('SECTION "ent_index", ROM0')
    out.append("EntBank:: db %d" % ENT_BANK)
    out.append("NumItemMeshes:: db %d" % len(ITEM_ORDER))
    out.append("ItemTab:: dw " + ",".join("Item%d" % i for i in range(len(ITEM_ORDER))))
    out.append("EnemyTab:: dw " + ",".join("Enemy%d" % i for i in range(len(ge.ENEMY_FILES))))
    open(os.path.join(outdir, "ents.inc"), "w", newline="\n").write("\n".join(out) + "\n")
    tests = enttests()
    t = ["; Generated by tools/gbc_genent.py - do not edit.", "DEF NumEntTests EQU %d" % len(tests),
         "EXPORT NumEntTests", "EntTestTab::"]
    for (kind, idx, frame, cx, cz, cy, cyaw, ox, oz, oy, oyaw) in tests:
        t.append("    db %d, %d, %d\n    dw %d, %d, %d\n    db %d\n    dw %d, %d, %d\n    db %d" %
                 (kind, idx, frame, cx, cz, cy, cyaw, ox, oz, oy, oyaw))
    open(os.path.join(outdir, "enttest.inc"), "w", newline="\n").write("\n".join(t) + "\n")
    print("entity meshes: %d items/doors, %d enemies, %d test cases" %
          (len(ITEM_ORDER), len(ge.ENEMY_FILES), len(tests)))


# ---- entity render test cases (ENTTEST builds) ------------------------------------------------

def enttests():
    """[(kind, idx, frame, camx, camz, camy, camyaw, ox, oz, oy, objyaw)] kind 0 item, 1 enemy."""
    import math
    items = ge.load_items()
    enemies = ge.load_enemies()
    cases = []
    n = 0

    def make(kind, idx, frame):
        nonlocal n
        camyaw = (n * 37) & 255
        dist = 6 + (n % 5) * 4
        off = ((n * 13) % 40 - 20) * 256 / 360.0 * 2 * math.pi / 256 * 1.0
        ang = (camyaw * 2 * math.pi / 256) + off
        cx, cz, cy = 30 * 256 + 17, 30 * 256 + 91, 38 * 256
        ox = int(cx + math.sin(ang) * dist * 256)
        oz = int(cz + math.cos(ang) * dist * 256)
        oy = 35 * 256
        cases.append((kind, idx, frame, cx, cz, cy, camyaw, ox, oz, oy, (n * 53) & 255))
        n += 1

    for i in range(len(ITEM_ORDER)):
        make(0, i, 0)
        make(0, i, 0)
    for ti, (key, _) in enumerate(ge.ENEMY_FILES):
        for f in range(0, len(enemies[key]["frames"]), 3):
            make(1, ti, f)
    # a few behind / far cases to exercise the cull
    cases.append((0, 11, 0, 30 * 256, 30 * 256, 38 * 256, 0, 30 * 256, 20 * 256, 35 * 256, 0))
    cases.append((1, 3, 0, 30 * 256, 30 * 256, 38 * 256, 0, 80 * 256, 45 * 256, 35 * 256, 7))
    return cases


def mesh_of(kind, idx, frame):
    """(verts, edges, shift, radius) as the ROM holds them."""
    if kind == 0:
        m = ge.load_items()[ITEM_ORDER[idx]]
        return m.verts, m.edges, m.shift, m.radius
    e = ge.load_enemies()[ge.ENEMY_FILES[idx][0]]
    return e["frames"][frame], e["edges"], 4, 3


if __name__ == "__main__":
    main()
