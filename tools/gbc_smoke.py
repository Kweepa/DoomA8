def scenario_chase(li, etype=0, closes=True):
    """No input: the enemy wakes, then closes in (or keeps its distance) and the player is hurt."""
    L = level(li)
    e, spot = pick_enemy(L, etype, dists=(10, 9, 11, 8, 12))
    if not e:
        print("  skip: no placeable enemy")
        return True
    px, pz, yaw = spot
    pack(L, li, e["room"], px, pz, yaw, e["y"], hp=250, frames=120, script=[0] * 120)
    r = run_rom()
    i = e["idx"]
    d0 = max(abs(e["x"] - px), abs(e["z"] - pz))
    d1 = max(abs(r["en_x"][i] - px), abs(r["en_z"][i] - pz))
    ok = check("woke", r["en_state"][i] != 0, "state %d" % r["en_state"][i])
    if closes:     # grunts and imps back off inside 8 cells, so only demons / barons must close in
        ok &= check("closed in", d1 < d0, "distance %d -> %d" % (d0, d1))
    ok &= check("player hurt", r["hp"] < 250, "hp %d" % r["hp"])
    return ok


def kick_expect(wid, e):
    """Weapon dy (px, down positive) e VBlanks after a shot: A8 recoil (native art) plus rest overhang."""
    def look(tab):
        for lim, dy in tab:
            if e < lim:
                return dy
        return 0
    if wid == 1:
        if 19 <= e < 34:
            return 5 if 21 <= e < 24 else 0
        return look([(1, -10), (3, 14), (5, 6)]) + 10
    if wid == 3:
        return look([(1, 24), (3, 16), (5, 8)])
    if wid == 4:
        return look([(18, -4), (28, -6)]) + 6
    return None


def scenario_recoil(wid):
    """Fire once, stop n frames later: the weapon offset follows the A8 recoil steps."""
    L = level(0)
    ok = True
    sx, sy, sz, _, sroom, _ = L.spawn
    for n in (1, 2, 4, 6, 12, 20, 22, 25, 30, 36, 40):
        pack(L, 0, sroom, sx, sz, 0, sy, wmask=0b111111, wcur=wid, hp=100, bul=50, shl=50, rkt=50,
             frames=n, dt=1, script=[0x10] + [0] * (n - 1))
        r = run_rom()
        want = kick_expect(wid, n - 1)
        ok &= check("dy at e=%d" % (n - 1), r["wdy"] == want, "got %d want %d" % (r["wdy"], want))
    return ok


