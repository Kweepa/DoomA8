#!/usr/bin/env python3
"""Headless gameplay scenarios for the GBC build (pickups, shooting, enemy AI, death).

  gbc_smoke.py [name ...]     (no name: run all)

Each scenario: generate gbc/build/smoke.inc, build the SMOKE ROM, run it in BGB, check the state
dump against what the rules (tools/gbc_game.py) predict or against plausibility bounds.
"""
import math
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import gbc_game as gg  # noqa: E402
import gbc_genmap as gmap  # noqa: E402
import gbc_world as gw  # noqa: E402
import gbc_losunit as los  # noqa: E402

ROOT = os.path.dirname(HERE)
LEVELS = {}


def level(li):
    if li not in LEVELS:
        keys = []
        for key in gmap.gm.LEVEL_NAMES:
            lv = gmap.gm.load_level(key)
            if any(o.get("kind") == "spawn" for o in (lv.get("objects") or [])):
                keys.append(key)
        lv = gmap.gm.load_level(keys[li])
        LEVELS[li] = gw.Level(gmap.gm.cook_one(lv, keys[li]))
    return LEVELS[li]


def things(L):
    return [dict(idx=t, type=L.f("th_type", t), x=L.f("th_x", t), y=L.f("th_y", t), z=L.f("th_z", t),
                 room=L.f("th_room", t)) for t in range(L.p[9])]


def enemies(L):
    return [dict(idx=i, type=L.f("en_type", i), x=L.f("en_x", i), y=L.f("en_y", i), z=L.f("en_z", i),
                 room=L.f("en_room", i), rot=L.f("en_rot", i), tag=L.f("en_tag", i)) for i in range(L.p[7])]


def room_at(L, cx, cz, cy):
    """First room containing the cell (same lookup as FindRoom)."""
    hit = [r for r in range(L.nrooms)
           if all(((val - L.f(pos, r)) & 255) < L.f(siz, r)
                  for pos, siz, val in (("room_x", "room_sx", cx), ("room_z", "room_sz", cz), ("room_y", "room_sy", cy)))]
    return hit[0] if len(hit) == 1 else 255     # ambiguous (overlapping rooms): not a usable spot


EN_DX = (0, 1, 1, 1, 0, -1, -1, -1)     # A8 en_dx / en_dz (octant 0 = +z, 2 = +x)
EN_DZ = (1, 1, 0, -1, -1, -1, 0, 1)


def a8_facing_ok(e, px, pz):
    """A8 enemy_facing_ok: within one cell, or not behind on either axis the en_dir octant needs."""
    dx, dz = px - e["x"], pz - e["z"]
    if max(abs(dx), abs(dz)) < 2:
        return True
    d = e["rot"] & 7
    if EN_DX[d] > 0 and dx < 0 or EN_DX[d] < 0 and dx > 0:
        return False
    if EN_DZ[d] > 0 and dz < 0 or EN_DZ[d] < 0 and dz > 0:
        return False
    return True


def place_near(L, e, dists=(6, 5, 7, 4, 8, 3), front=True, back=False):
    """A walkable player spot 3-8 cells from enemy e (inside the room's collider inset). front: the
    A8 facing test passes (it sees the player); back: it fails (it does not)."""
    for d in dists:
        for k in range(0, 256, 32):
            ang = k * 2 * math.pi / 256
            px = int(round(e["x"] + math.sin(ang) * d))
            pz = int(round(e["z"] + math.cos(ang) * d))
            if not (0 <= px < 256 and 0 <= pz < 256):
                continue
            # A8 facing test with a one-cell margin (the ROM may settle the player a cell over)
            near = [(px + ax, pz + az) for ax in (-1, 0, 1) for az in (-1, 0, 1)]
            if front and not all(a8_facing_ok(e, x, z) for x, z in near):
                continue
            if back and any(a8_facing_ok(e, x, z) for x, z in near):
                continue
            P = gw.Player(L, e["room"], px * 256 + 128, pz * 256 + 128, (e["y"] + 3) * 256, 0, e["y"])
            if (gw.in_room_inset(P, px, pz) and not gw.solid_at(P, px, pz)
                    and room_at(L, px, pz, e["y"] + 3) == e["room"]
                    and not los.blocked(L, e["room"], [px, e["y"] + 3, pz], [e["x"], e["y"] + 3, e["z"]])):
                yaw = gg.angle_to((e["x"] - px) * 256 - 128, (e["z"] - pz) * 256 - 128)   # player at the cell centre
                return px, pz, yaw
    return None


def pack(L, li, room, px, pz, yaw, floor_y, *, keys=0, wmask=0b010001, wcur=4, hp=100, bul=50, shl=25,
         rkt=0, frames=10, dt=3, script=None, lift=0):
    script = script or [0] * frames
    assert len(script) <= 255, "frames is a byte"
    out = ["; Generated by tools/gbc_smoke.py - do not edit.", "SmokeScenario::"]
    out.append("    db %d, %d\n    dw %d, %d, %d\n    db %d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d" %
               (li, room, px * 256 + 128, pz * 256 + 128, (floor_y + 3 + lift) * 256, yaw, floor_y, keys, wmask, wcur,
                hp, bul, shl, rkt, len(script), dt))
    for k in range(0, len(script), 16):
        out.append("    db " + ",".join(str(b) for b in script[k:k + 16]))
    open(os.path.join(ROOT, "gbc", "build", "smoke.inc"), "w", newline="\n").write("\n".join(out) + "\n")


def run_rom():
    # The smoke ROM draws the scene every frame (RenderScene + DrawWorldObjects), so a draw-path hang with
    # awake enemies is caught; the VBlank wait / DMA path is not part of it (WaitVBlank hangs in this ROM).
    os.environ["GBC_DEFS"] = "-D SMOKEDRAW=1 -D SDNODISP=1 -D SDAPPLY=1"
    subprocess.run(["cmd", "/c", os.path.join(ROOT, "build-gbc.bat"), "smoke"], check=True,
                   stdout=subprocess.DEVNULL)
    rom = os.path.join(ROOT, "gbc", "build", "doomgbc_smoke.gbc")
    state = os.path.join(ROOT, "gbc", "build", "smoke.sna")
    bgb = os.environ.get("GBEMU", r"C:\dev\tools\bgb\bgb64.exe")
    addr = None
    for line in open(os.path.splitext(rom)[0] + ".sym"):
        if line.strip().endswith(" MainLoop"):
            addr = line.split()[0].split(":")[1]
    if os.path.exists(state):
        os.remove(state)
    subprocess.run([bgb, "-hf", "-nobatt", "-rom", rom, "-br", addr, "-stateonexit", state], timeout=10)
    data = open(state, "rb").read()
    i = data.find(b"POSE")
    base = i + 4 + 2
    d = data[base:base + 477]
    return dict(hp=d[0], armor=d[1], kills=d[2], bul=d[3], shl=d[4], rkt=d[5], have=d[6], keys=d[7], wcur=d[8],
                room=d[9], camx=d[10] | d[11] << 8, camz=d[12] | d[13] << 8, camy=d[14] | d[15] << 8,
                floor=d[16], falling=d[17], level=d[18], nen=d[19], wdy=d[26] - (256 if d[26] > 127 else 0), th=list(d[32:64]),
                en_state=list(d[64:88]), en_hp=list(d[88:112]), en_x=list(d[112:136]), en_z=list(d[136:160]),
                en_frame=list(d[160:184]), en_rot=list(d[184:208]), en_dir=list(d[208:232]),
                en_timer=list(d[232:256]), gunshot=d[256], pr_on=list(d[257:261]), pr_x=list(d[261:265]),
                pr_z=list(d[265:269]), pr_life=list(d[269:273]), pr_v=list(d[273:277]), ang=d[277],
                pr_fr=list(d[278:280]), hud=list(d[280:360]), hurt_ms=d[360] | d[361] << 8, border=d[362],
                status_ms=d[363] | d[364] << 8, raw_dt=d[365],
                emuz_seen=d[366], emuz_lod=d[367], emuz_col=d[368], emuz_y=d[369],
                door_key=list(d[370:402:2]), door_type=list(d[371:402:2]),
                elev_y=list(d[402:410]), elev_tgt=list(d[410:418]), on_elev=d[418],
                fx_ms=d[419] | d[420] << 8, fx_plots=d[421], fx_vx=list(d[422:446]), fx_vy=list(d[446:470]),
                splat_seen=d[470], splat_col=d[471], splat_ms=d[472], splat_at=tuple(d[473:476]), splat_drawn=d[476])


def check(name, cond, msg):
    print("  %s %s: %s" % ("ok  " if cond else "FAIL", name, msg))
    return cond


TH_NAMES = ["stimpack", "medikit", "security armor", "combat armor", "ammo box", "shells", "box of rockets",
            "shotgun", "chaingun", "chainsaw", "rocket launcher", "backpack", "[ keycard", r"\ keycard",
            "] keycard", "soulsphere", "radsuit", "lightpost", "barrel"]     # A8 hud.asm thn_*


def frame_ms(n):
    """gbc/hud.asm FrameMs: VBlanks * 16.75 (17n - n/4), 255 from 16 VBlanks up."""
    return 255 if n >= 16 else 17 * n - n // 4


def hud_rows(hp, armor, bul, shl, rkt, keys, raw_dt, msg=""):
    """The GBC HUD (gbc/hud.asm) as tile ids (ASCII - 32), Doom-style block:
    row 14 message (centred); ammo column (cols 2-5, rows 15-17); health (row 16, cols 7-10); armour
    (row 16, cols 12-15) with "ms" + frame time under it; key column (col 17): blue, yellow, red."""
    row = lambda: [" "] * 20

    def put(r, col, icon, v):
        r[col] = icon
        r[col + 1:col + 4] = list("%03d" % v)
    r14, r15, r16, r17 = row(), row(), row(), row()
    msg = msg[:20]
    c = (20 - len(msg)) // 2
    r14[c:c + len(msg)] = list(msg)
    put(r15, 2, "{", bul)
    put(r16, 2, "|", shl)
    put(r17, 2, "}", rkt)
    put(r16, 7, "^", hp)
    put(r16, 12, "~", armor)
    r17[11:13] = ["m", "s"]
    r17[13:16] = list("%03d" % frame_ms(raw_dt))
    if keys & 2:
        r15[17] = "]"
    if keys & 1:
        r16[17] = "\\"
    if keys & 4:
        r17[17] = "["
    return [ord(ch) - 32 for ch in r14 + r15 + r16 + r17]


def hud_text(ids):
    return "|".join("".join(chr(i + 32) for i in ids[k:k + 20]) for k in (0, 20, 40, 60))


def scenario_pickups(li):
    """Stand on the first pickup of the level: it is used up and applied per the A8 rules (gb_*)."""
    L = level(li)
    pk = [t for t in things(L) if t["type"] <= 16]
    t = pk[0]
    P = gg.PlayerState()
    used = gg.apply_pickup(P, t["type"])
    pack(L, li, t["room"], t["x"], t["z"], 0, t["y"], frames=4)
    r = run_rom()
    ok = check("taken" if used else "left on the floor", r["th"][t["idx"]] == (1 if used else 0),
               "thing %d type %d" % (t["idx"], t["type"]))
    got = (r["hp"], r["armor"], r["bul"], r["shl"], r["rkt"], r["have"], r["keys"])
    ok &= check("state", got == P.tup()[:7], "got %s want %s" % (got, P.tup()[:7]))
    msg = "+" + TH_NAMES[t["type"]] if used else ""
    want = hud_rows(r["hp"], r["armor"], r["bul"], r["shl"], r["rkt"], r["keys"], r["raw_dt"], msg)
    ok &= check("hud", r["hud"] == want, "got %r want %r" % (hud_text(r["hud"]), hud_text(want)))
    ok &= check("message timer", (0 < r["status_ms"] <= 5000) == used, "status_ms %d" % r["status_ms"])
    return ok


def scenario_refused(types, **state):
    """A8 gb_*: an item that cannot be used (health at 100, armour at 200) stays on the floor and shows
    no message; the player is unchanged."""
    for li in range(8):
        L = level(li)
        for t in things(L):
            if t["type"] in types:
                pack(L, li, t["room"], t["x"], t["z"], 0, t["y"], frames=4, **state)
                r = run_rom()
                ok = check("left on the floor", r["th"][t["idx"]] == 0, "level %d thing %d type %d" % (li, t["idx"], t["type"]))
                ok &= check("no message", r["status_ms"] == 0, "status_ms %d" % r["status_ms"])
                return ok
    print("  skip: no such pickup")
    return True


def scenario_fall(lift, want_dmg):
    """A8 update_fall: an eye drop over FALL_SAFE (8) costs FALL_DAMAGE (15) HP on landing."""
    L = level(0)
    sx, sy, sz, _, sroom, _ = L.spawn
    pack(L, 0, sroom, sx, sz, 0, sy, frames=40, dt=2, lift=lift, hp=100)
    r = run_rom()
    return check("fall of %d" % lift, r["hp"] == 100 - want_dmg and not r["falling"], "hp %d falling %d" % (r["hp"], r["falling"]))


def pick_enemy(L, etype, rots=None, **kw):
    for e in enemies(L):
        if rots is not None and (e["rot"] & 7) not in rots:
            continue
        if e["type"] == etype and not e["tag"]:    # tagged enemies are EN_GONE until a trigger
            spot = place_near(L, e, **kw)
            if spot:
                return e, spot
    return None, None


def scenario_shoot(li, etype=0):
    """Pistol held down at a possessed: it dies and the kill count goes up."""
    L = level(li)
    e, spot = pick_enemy(L, etype)
    if not e:
        print("  skip: no placeable enemy of type %d in level %d" % (etype, li))
        return True
    px, pz, yaw = spot
    pack(L, li, e["room"], px, pz, yaw, e["y"], wmask=0b010101, wcur=2, hp=100, bul=200, frames=200, script=[0x10] * 200)   # chaingun: the pistol now fires every 600 ms
    r = run_rom()
    ok = check("enemy dead or dying", r["en_state"][e["idx"]] in (6, 7), "state %d hp %d" % (r["en_state"][e["idx"]], r["en_hp"][e["idx"]]))
    ok &= check("kill counted", r["kills"] >= 1, "kills %d" % r["kills"])
    if r["en_state"][e["idx"]] == 7:
        dl = A8_META[etype][24]
        ok &= check("corpse on the last death frame", r["en_frame"][e["idx"]] == dl - 1,
                    "frame %d, death clip %d frames" % (r["en_frame"][e["idx"]], dl))
    ok &= check("ammo spent", r["bul"] < 200, "bullets %d" % r["bul"])
    return ok


def scenario_attack(li, etype=0):
    """No input: the enemy wakes, chases and hurts the player."""
    L = level(li)
    e, spot = pick_enemy(L, etype)
    if not e:
        print("  skip: no placeable enemy")
        return True
    px, pz, yaw = spot
    pack(L, li, e["room"], px, pz, yaw, e["y"], hp=100, frames=240, script=[0] * 240)
    r = run_rom()
    ok = check("player hurt", r["hp"] < 100, "hp %d" % r["hp"])
    ok &= check("border follows hurt timer", r["border"] == (0x48 if r["hurt_ms"] else 0) and r["hurt_ms"] <= 300,
                "border $%02X hurt_ms %d" % (r["border"], r["hurt_ms"]))
    moved = (r["en_x"][e["idx"]], r["en_z"][e["idx"]]) != (e["x"], e["z"])
    ok &= check("enemy moved / woke", moved or r["en_state"][e["idx"]] != 0, "state %d pos %s" % (r["en_state"][e["idx"]], (r["en_x"][e["idx"]], r["en_z"][e["idx"]])))
    return ok


def scenario_muzzle(li, etype, want):
    """A8 enemy_muzzle_want: a possessed shooting / an imp throwing starts the red muzzle stamp at its
    weapon vertex (LOD by depth, box inside the viewport); a pinky bite never does."""
    L = level(li)
    e, spot = pick_enemy(L, etype, dists=(4, 3, 5) if etype == 2 else (8, 7, 9, 6, 10))
    if not e:
        print("  skip: no placeable enemy")
        return True
    px, pz, yaw = spot
    pack(L, li, e["room"], px, pz, yaw, e["y"], hp=250, frames=120, script=[0] * 120)
    r = run_rom()
    if not want:
        return check("no muzzle", r["emuz_seen"] == 0, "starts %d" % r["emuz_seen"])
    ok = check("muzzle started", r["emuz_seen"] > 0, "starts %d (hp %d)" % (r["emuz_seen"], r["hp"]))
    ok &= check("box in the viewport", r["emuz_lod"] <= 2 and r["emuz_col"] <= 13 and r["emuz_y"] <= 112 - 21,
                "lod %d col %d y %d" % (r["emuz_lod"], r["emuz_col"], r["emuz_y"]))
    return ok


def scenario_weapon(wid, dists, yaw_off, frames, expect, etype=0):
    """A8 hit rules. expect: 'dead' (the enemy dies), 'hurt' (takes damage), 'miss' (untouched).
    yaw_off turns the view away from the enemy (units of 1/256 turn)."""
    L = level(1)
    e, spot = pick_enemy(L, etype, dists=dists)
    if not e:
        print("  skip: no placeable enemy")
        return True
    px, pz, yaw = spot
    pack(L, 1, e["room"], px, pz, (yaw + yaw_off) & 255, e["y"], wmask=0b111111, wcur=wid, hp=250, bul=200, shl=50,
         frames=frames, script=[0x10] * frames)
    r = run_rom()
    i = e["idx"]
    st, hp0 = r["en_state"][i], A8_META[etype][34]
    if expect == "dead":
        return check("dead", st in (6, 7), "state %d hp %d" % (st, r["en_hp"][i]))
    if expect == "hurt":
        return check("hurt", r["en_hp"][i] < hp0, "hp %d of %d" % (r["en_hp"][i], hp0))
    return check("untouched", r["en_hp"][i] == hp0 and r["kills"] == 0, "hp %d of %d kills %d" % (r["en_hp"][i], hp0, r["kills"]))


def place_for_target(L, room, tx, ty, tz, dists=(5, 4, 6, 7, 3)):
    """A walkable player spot with a clear line to the cell (tx, ty, tz), and the yaw that looks at it."""
    for d in dists:
        for k in range(0, 256, 16):
            ang = k * 2 * math.pi / 256
            px = int(round(tx + math.sin(ang) * d))
            pz = int(round(tz + math.cos(ang) * d))
            if not (0 <= px < 256 and 0 <= pz < 256):
                continue
            P = gw.Player(L, room, px * 256 + 128, pz * 256 + 128, (ty + 3) * 256, 0, ty)
            if (gw.in_room_inset(P, px, pz) and not gw.solid_at(P, px, pz) and room_at(L, px, pz, ty + 3) == room
                    and not los.blocked(L, room, [px, ty + 3, pz], [tx, ty + 1, tz])):
                return px, pz, gg.angle_to(tx * 256 - px * 256 - 128, tz * 256 - pz * 256 - 128)
    return None


def barrels(L):
    return [t for t in things(L) if t["type"] == 18]


def scenario_barrel(li, wid):
    """A8 barrel_explode: a shot barrel is gone at once (taken) and takes enemies within RKT_RAD with it."""
    L = level(li)
    for b in barrels(L):
        spot = place_for_target(L, b["room"], b["x"] + 1, b["y"], b["z"] + 1)
        if spot:
            px, pz, yaw = spot
            pack(L, li, b["room"], px, pz, yaw, b["y"], wmask=0b111111, wcur=wid, hp=250, bul=200, shl=50, rkt=20,
                 frames=6, script=[0x10] * 6)
            r = run_rom()
            return check("barrel exploded", r["th"][b["idx"]] == 1, "thing %d level %d" % (b["idx"], li))
    print("  skip: no barrel with a clear line in level %d" % li)
    return True


def scenario_rocket(li, etype):
    """A8 rocket: a player rocket flies along the view and explodes on the first enemy: 16..47 splash."""
    L = level(li)
    e, spot = pick_enemy(L, etype, dists=(8, 7, 9, 6, 10))
    if not e:
        print("  skip: no placeable enemy")
        return True
    px, pz, yaw = spot
    pack(L, li, e["room"], px, pz, yaw, e["y"], wmask=0b111111, wcur=3, hp=250, bul=50, shl=0, rkt=5,
         frames=12, script=[0x10] + [0] * 11)
    r = run_rom()
    hp0 = A8_META[etype][34]
    ok = check("rocket spent", r["rkt"] == 4, "rockets %d" % r["rkt"])
    sv = lambda v: v - 256 if v > 127 else v
    vmax = max(max(abs(sv(v)) for v in r["fx_vx"]), max(abs(sv(v)) for v in r["fx_vy"]))
    ok &= check("explosion running", 0 < r["fx_ms"] <= 668, "time left %d ms" % r["fx_ms"])
    ok &= check("particles plotted", r["fx_plots"] > 0, "%d pixels drawn" % r["fx_plots"])
    ok &= check("24 particle velocities picked", 0 < vmax <= 32 and any(r["fx_vx"]) and any(r["fx_vy"]), "max |v| %d" % vmax)
    ok &= check("enemy hurt", r["en_hp"][e["idx"]] != hp0 and r["en_state"][e["idx"]] >= 5, "hp %d of %d" % (r["en_hp"][e["idx"]], hp0))
    return ok


def scenario_barrel_splash(li):
    """A barrel next to an enemy: shooting it hurts the enemy (blast radius RKT_RAD, 16..47)."""
    L = level(li)
    for b in barrels(L):
        for e in enemies(L):
            if e["room"] != b["room"] or e["tag"]:
                continue
            if max(abs(e["x"] - b["x"] - 1), abs(e["z"] - b["z"] - 1), abs(e["y"] - b["y"] - 1)) < 8:
                spot = place_for_target(L, b["room"], b["x"] + 1, b["y"], b["z"] + 1)
                if spot:
                    px, pz, yaw = spot
                    pack(L, li, b["room"], px, pz, yaw, b["y"], wmask=0b111111, wcur=4, hp=250, bul=200, frames=6,
                         script=[0x10] * 6)
                    r = run_rom()
                    hp0 = A8_META[e["type"]][34]
                    ok = check("barrel exploded", r["th"][b["idx"]] == 1, "thing %d" % b["idx"])
                    ok &= check("enemy in the blast hurt", r["en_hp"][e["idx"]] != hp0, "hp %d of %d" % (r["en_hp"][e["idx"]], hp0))
                    return ok
    print("  skip: no barrel near an enemy with a clear line in level %d" % li)
    return True


def triggers(L):
    return [dict(idx=i, room=L.f("tr_room", i), pur=L.f("tr_purpose", i), arg=L.f("tr_arg", i),
                 x=L.f("tr_x", i), y=L.f("tr_y", i), z=L.f("tr_z", i), sx=L.f("tr_sx", i), sy=L.f("tr_sy", i),
                 sz=L.f("tr_sz", i)) for i in range(L.p[8])]


def stand_in(L, li, t, frames=12, **kw):
    """Run with the player standing in the middle of trigger t."""
    px, pz = t["x"] + t["sx"] // 2, t["z"] + t["sz"] // 2
    pack(L, li, t["room"], px, pz, 0, t["y"], frames=frames, dt=3, **kw)
    return run_rom()


def scenario_trigger(li, pur, **want):
    """A8 trig_enter on the first trigger of that purpose in level li."""
    L = level(li)
    t = next((t for t in triggers(L) if t["pur"] == pur and t["sy"] >= 2), None)    # tall enough to stand in
    if not t:
        print("  skip: no such trigger")
        return True
    r = stand_in(L, li, t, frames=want.get("frames", 12))
    ok = True
    if "level" in want:
        ok &= check("level now %d" % want["level"], r["level"] == want["level"], "level %d" % r["level"])
    if "hp_lost" in want:
        ok &= check("hurt volume", r["hp"] == 100 - want["hp_lost"], "hp %d" % r["hp"])
    if want.get("spawn"):
        tags = {i: L.f("en_tag", i) for i in range(L.p[7])}
        gone = [i for i, tg in tags.items() if tg == t["arg"]]
        ok &= check("tagged enemies woke", gone and all(r["en_state"][i] != 8 for i in gone), "enemies %s states %s" % (gone, [r["en_state"][i] for i in gone]))
    if want.get("unlock"):
        doors = [d for d in range(L.p[1]) if L.f("door_tag", d) == t["arg"] and L.f("door_key", d) == 3]
        ok &= check("remote doors unlocked", doors and all(r["door_key"][d] == 0 for d in doors if d < 16),
                    "doors %s keys %s" % (doors, [r["door_key"][d] for d in doors if d < 16]))
    return ok


def elevs(L):
    return [dict(idx=i, room=L.f("elev_room", i), x=L.f("elev_x", i), y0=L.f("elev_y0", i), z=L.f("elev_z", i),
                 sx=L.f("elev_sx", i), sy=L.f("elev_sy", i), sz=L.f("elev_sz", i), home=L.f("elev_home", i),
                 dest=L.f("elev_dest", i), grp=L.f("elev_grp", i)) for i in range(L.p[6])]


def scenario_elevator_trigger(li):
    """A8 trig_enter TRIG_ELEV: entering the trigger starts every car of its group toward the other stop; the
    car moves one unit per ELEV_STEP_MS and its height changes."""
    L = level(li)
    t = next((t for t in triggers(L) if t["pur"] == 4 and t["sy"] >= 2 and any(e["grp"] == t["arg"] for e in elevs(L))), None)
    if not t:
        print("  skip: no elevator trigger")
        return True
    cars = [e for e in elevs(L) if e["grp"] == t["arg"]]
    r = stand_in(L, li, t, frames=30)
    moved = [c for c in cars if r["elev_y"][c["idx"]] != c["y0"] or r["elev_tgt"][c["idx"]] != 255]
    return check("car of group %d moving" % t["arg"], len(moved) > 0,
                 "cars %s y %s tgt %s" % ([c["idx"] for c in cars], [r["elev_y"][c["idx"]] for c in cars], [r["elev_tgt"][c["idx"]] for c in cars]))


def scenario_ride(li):
    """Standing on a car that goes up: the player's feet follow its top (A8 elev_update_floor)."""
    L = level(li)
    for e in elevs(L):
        if e["dest"] != e["home"]:
            px, pz = e["x"] + e["sx"] // 2, e["z"] + e["sz"] // 2
            top0 = e["y0"] + e["sy"]
            pack(L, li, e["room"], px, pz, 0, top0, frames=2, dt=3)
            r = run_rom()
            return check("boarded", r["on_elev"] == e["idx"] and r["floor"] == top0,
                         "on_elev %d floor %d top %d" % (r["on_elev"], r["floor"], top0))
    print("  skip: no elevator")
    return True


