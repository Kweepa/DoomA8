#!/usr/bin/env python3
"""Headless gameplay scenarios for the GBC build (pickups, shooting, enemy AI, death).

  gbc_smoke.py [name ...]     (no name: run all)

Each scenario: generate gbc/build/smoke.inc, build the SMOKE ROM, run it in BGB, check the state
dump against what the rules (tools/gbc_game.py) predict or against plausibility bounds.
"""
import math
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import gbc_game as gg  # noqa: E402
import gbc_genmap as gmap  # noqa: E402
import gbc_world as gw  # noqa: E402

ROOT = os.path.dirname(HERE)
LEVELS = {}


def level(li):
    if li not in LEVELS:
        keys = []
        for key in gmap.gm.LEVEL_NAMES:
            lv = gmap.gm.load_level(key)
            if any(o.get("kind") == "spawn" for o in (lv.get("objects") or [])):
                keys.append(key)
        lv = gmap.gm.load_level(keys[li])
        LEVELS[li] = gw.Level(gmap.gm.cook_one(lv, keys[li]))
    return LEVELS[li]


def things(L):
    return [dict(idx=t, type=L.f("th_type", t), x=L.f("th_x", t), y=L.f("th_y", t), z=L.f("th_z", t),
                 room=L.f("th_room", t)) for t in range(L.p[9])]


def enemies(L):
    return [dict(idx=i, type=L.f("en_type", i), x=L.f("en_x", i), y=L.f("en_y", i), z=L.f("en_z", i),
                 room=L.f("en_room", i), rot=L.f("en_rot", i)) for i in range(L.p[7])]


def room_at(L, cx, cz, cy):
    """First room containing the cell (same lookup as FindRoom)."""
    hit = [r for r in range(L.nrooms)
           if all(((val - L.f(pos, r)) & 255) < L.f(siz, r)
                  for pos, siz, val in (("room_x", "room_sx", cx), ("room_z", "room_sz", cz), ("room_y", "room_sy", cy)))]
    return hit[0] if len(hit) == 1 else 255     # ambiguous (overlapping rooms): not a usable spot


def place_near(L, e, dists=(6, 5, 7, 4, 8, 3), front=True, back=False):
    """A walkable player spot 3-8 cells from enemy e (inside the room's collider inset). front: in
    the enemy's facing half-plane (it sees the player); back: behind it (it does not)."""
    facing = (-e["rot"] * 32) & 255
    for d in dists:
        for k in range(0, 256, 32):
            ang = k * 2 * math.pi / 256
            px = int(round(e["x"] + math.sin(ang) * d))
            pz = int(round(e["z"] + math.cos(ang) * d))
            if not (0 <= px < 256 and 0 <= pz < 256):
                continue
            head = gg.angle_to(px - e["x"], pz - e["z"])
            diff = ((head - facing + 128) & 255) - 128
            if front and abs(diff) > 40:
                continue
            if back and abs(diff) < 100:
                continue
            P = gw.Player(L, e["room"], px * 256 + 128, pz * 256 + 128, (e["y"] + 3) * 256, 0, e["y"])
            if gw.in_room_inset(P, px, pz) and room_at(L, px, pz, e["y"] + 3) == e["room"]:
                yaw = gg.angle_to(e["x"] - px, e["z"] - pz)
                return px, pz, yaw
    return None


def pack(L, li, room, px, pz, yaw, floor_y, *, keys=0, wmask=0b010001, wcur=4, hp=100, bul=50, shl=0,
         rkt=0, frames=10, dt=3, script=None):
    script = script or [0] * frames
    assert len(script) <= 255, "frames is a byte"
    out = ["; Generated by tools/gbc_smoke.py - do not edit.", "SmokeScenario::"]
    out.append("    db %d, %d\n    dw %d, %d, %d\n    db %d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d" %
               (li, room, px * 256 + 128, pz * 256 + 128, (floor_y + 3) * 256, yaw, floor_y, keys, wmask, wcur,
                hp, bul, shl, rkt, len(script), dt))
    for k in range(0, len(script), 16):
        out.append("    db " + ",".join(str(b) for b in script[k:k + 16]))
    open(os.path.join(ROOT, "gbc", "build", "smoke.inc"), "w", newline="\n").write("\n".join(out) + "\n")


def run_rom():
    # The smoke ROM draws the scene every frame (RenderScene + DrawWorldObjects), so a draw-path hang with
    # awake enemies is caught; the VBlank wait / DMA path is not part of it (WaitVBlank hangs in this ROM).
    os.environ["GBC_DEFS"] = "-D SMOKEDRAW=1 -D SDNODISP=1 -D SDAPPLY=1"
    subprocess.run(["cmd", "/c", os.path.join(ROOT, "build-gbc.bat"), "smoke"], check=True,
                   stdout=subprocess.DEVNULL)
    rom = os.path.join(ROOT, "gbc", "build", "doomgbc_smoke.gbc")
    state = os.path.join(ROOT, "gbc", "build", "smoke.sna")
    bgb = os.environ.get("GBEMU", r"C:\dev\tools\bgb\bgb64.exe")
    addr = None
    for line in open(os.path.splitext(rom)[0] + ".sym"):
        if line.strip().endswith(" MainLoop"):
            addr = line.split()[0].split(":")[1]
    if os.path.exists(state):
        os.remove(state)
    subprocess.run([bgb, "-hf", "-nobatt", "-rom", rom, "-br", addr, "-stateonexit", state], timeout=60)
    data = open(state, "rb").read()
    i = data.find(b"POSE")
    base = i + 4 + 2
    d = data[base:base + 160]
    return dict(hp=d[0], armor=d[1], kills=d[2], bul=d[3], shl=d[4], rkt=d[5], have=d[6], keys=d[7], wcur=d[8],
                room=d[9], camx=d[10] | d[11] << 8, camz=d[12] | d[13] << 8, camy=d[14] | d[15] << 8,
                floor=d[16], falling=d[17], level=d[18], nen=d[19], th=list(d[32:64]),
                en_state=list(d[64:88]), en_hp=list(d[88:112]), en_x=list(d[112:136]), en_z=list(d[136:160]))


def check(name, cond, msg):
    print("  %s %s: %s" % ("ok  " if cond else "FAIL", name, msg))
    return cond


def scenario_pickups(li):
    """Stand on the first pickup of the level: it is taken and applied per the spec rules."""
    L = level(li)
    pk = [t for t in things(L) if t["type"] <= 16]
    t = pk[0]
    P = gg.PlayerState()
    gg.apply_pickup(P, t["type"])
    pack(L, li, t["room"], t["x"], t["z"], 0, t["y"], frames=4)
    r = run_rom()
    ok = check("taken", r["th"][t["idx"]] == 1, "thing %d type %d" % (t["idx"], t["type"]))
    ok &= check("state", (r["hp"], r["armor"], r["bul"], r["shl"], r["rkt"], r["have"], r["keys"]) == P.tup(),
                "got %s want %s" % ((r["hp"], r["armor"], r["bul"], r["shl"], r["rkt"], r["have"], r["keys"]), P.tup()))
    return ok


def pick_enemy(L, etype, **kw):
    for e in enemies(L):
        if e["type"] == etype:
            spot = place_near(L, e, **kw)
            if spot:
                return e, spot
    return None, None


def scenario_shoot(li, etype=0):
    """Pistol held down at a possessed: it dies and the kill count goes up."""
    L = level(li)
    e, spot = pick_enemy(L, etype)
    if not e:
        print("  skip: no placeable enemy of type %d in level %d" % (etype, li))
        return True
    px, pz, yaw = spot
    pack(L, li, e["room"], px, pz, yaw, e["y"], wcur=4, hp=100, bul=200, frames=200, script=[0x10] * 200)
    r = run_rom()
    ok = check("enemy dead or dying", r["en_state"][e["idx"]] in (4, 7), "state %d hp %d" % (r["en_state"][e["idx"]], r["en_hp"][e["idx"]]))
    ok &= check("kill counted", r["kills"] >= 1, "kills %d" % r["kills"])
    ok &= check("ammo spent", r["bul"] < 200, "bullets %d" % r["bul"])
    return ok


def scenario_attack(li, etype=0):
    """No input: the enemy wakes, chases and hurts the player."""
    L = level(li)
    e, spot = pick_enemy(L, etype)
    if not e:
        print("  skip: no placeable enemy")
        return True
    px, pz, yaw = spot
    pack(L, li, e["room"], px, pz, yaw, e["y"], hp=100, frames=240, script=[0] * 240)
    r = run_rom()
    ok = check("player hurt", r["hp"] < 100, "hp %d" % r["hp"])
    moved = (r["en_x"][e["idx"]], r["en_z"][e["idx"]]) != (e["x"], e["z"])
    ok &= check("enemy moved / woke", moved or r["en_state"][e["idx"]] != 0, "state %d pos %s" % (r["en_state"][e["idx"]], (r["en_x"][e["idx"]], r["en_z"][e["idx"]])))
    return ok


def scenario_death(li, etype=3):
    """Low HP, no input: the player dies, then the level reloads with a fresh player."""
    L = level(li)
    e, spot = pick_enemy(L, etype)
    if not e:
        e, spot = pick_enemy(L, 0)
    px, pz, yaw = spot
    pack(L, li, e["room"], px, pz, yaw, e["y"], hp=3, frames=250, script=[0] * 250)
    r = run_rom()
    reloaded = r["hp"] > 3 and r["room"] == L.p[21]   # fresh player (may already be hit again)
    return check("died and reloaded", reloaded, "hp %d room %d (spawn room %d)" % (r["hp"], r["room"], L.p[21]))


def scenario_unseen(li, etype=0):
    """The player stands behind an idle enemy and does nothing: it stays idle."""
    L = level(li)
    e, spot = pick_enemy(L, etype, front=False, back=True)
    if not e:
        print("  skip: no placeable enemy behind")
        return True
    px, pz, yaw = spot
    pack(L, li, e["room"], px, pz, yaw, e["y"], hp=100, frames=120, script=[0] * 120)
    r = run_rom()
    return check("still idle", r["en_state"][e["idx"]] == 0 and r["hp"] == 100, "state %d hp %d" % (r["en_state"][e["idx"]], r["hp"]))


def scenario_chase(li, etype=0, closes=True):
    """No input: the enemy wakes, then closes in (or keeps its distance) and the player is hurt."""
    L = level(li)
    e, spot = pick_enemy(L, etype, dists=(10, 9, 11, 8, 12))
    if not e:
        print("  skip: no placeable enemy")
        return True
    px, pz, yaw = spot
    pack(L, li, e["room"], px, pz, yaw, e["y"], hp=250, frames=120, script=[0] * 120)
    r = run_rom()
    i = e["idx"]
    d0 = max(abs(e["x"] - px), abs(e["z"] - pz))
    d1 = max(abs(r["en_x"][i] - px), abs(r["en_z"][i] - pz))
    ok = check("woke", r["en_state"][i] != 0, "state %d" % r["en_state"][i])
    if closes:     # grunts and imps back off inside 8 cells, so only demons / barons must close in
        ok &= check("closed in", d1 < d0, "distance %d -> %d" % (d0, d1))
    ok &= check("player hurt", r["hp"] < 250, "hp %d" % r["hp"])
    return ok


SCENARIOS = {
    "pickups_e1m1": lambda: scenario_pickups(0),
    "pickups_e1m2": lambda: scenario_pickups(1),
    "pickups_e1m5": lambda: scenario_pickups(4),
    "shoot_poss_e1m2": lambda: scenario_shoot(1, 0),
    "shoot_imp_e1m2": lambda: scenario_shoot(1, 3),
    "attack_poss_e1m2": lambda: scenario_attack(1, 0),
    "attack_pinky_e1m2": lambda: scenario_attack(1, 2),
    "death_e1m2": lambda: scenario_death(1, 0),
    "unseen_poss_e1m2": lambda: scenario_unseen(1, 0),
    "chase_poss_e1m2": lambda: scenario_chase(1, 0, closes=False),
    "chase_imp_e1m2": lambda: scenario_chase(1, 3, closes=False),
    "chase_pinky_e1m3": lambda: scenario_chase(2, 2),
    "chase_baron_e1m8": lambda: scenario_chase(7, 1),
}


def main():
    names = sys.argv[1:] or list(SCENARIOS)
    failed = []
    for n in names:
        print(n)
        try:
            if not SCENARIOS[n]():
                failed.append(n)
        except subprocess.TimeoutExpired:
            print("  FAIL hang: the ROM never reached MainLoop")
            failed.append(n)
        finally:
            subprocess.run(["taskkill", "/F", "/IM", "bgb64.exe"], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    print("smoke scenarios: %d, failed: %d %s" % (len(names), len(failed), failed))
    sys.exit(1 if failed else 0)


if __name__ == "__main__":
    main()
