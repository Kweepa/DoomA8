#!/usr/bin/env python3
"""Weapon view-model sprites for the GBC: editor sprite art -> scaled 8x16 OAM cells.

Source art: the "gbSprites" list in editor/doom64.json (edited in the editor's GB Sprites tab;
rows of "." / "#", "#" = ink), used at native size (1:1) in the 128 x 112 GBC viewport.

Writes <outdir>/wpn.inc:
  bank WPN_BANK: for every frame  db ncells, w, h ; ncells * (db dy, x, tile) placements, where x is the
                 absolute OAM x and tile the OAM tile id (the VBlank OAM loop reads them straight from ROM);
                 tile data (32 bytes per cell) is a separate 16-byte-aligned run
                 (a cell is one 8x16 sprite: top tile then bottom tile, 2bpp, ink = colour 1)
  ROM0: WpnFrameTab (dw per frame), WpnBank, frame ids as DEF WF_* constants (wpn_ids.inc)
Frame data is uploaded to VRAM when the frame changes: body frames to bank 1 ids 224.., flash
frames to bank 0 ids 242.. (see gbc/wpn.asm).
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
DOC = os.path.join(ROOT, "editor", "doom64.json")
WPN_BANK = 12

# Must match gbc/wpn.asm: art is centred in the 128 px viewport that starts at screen x VIEW_X0; OAM x
# carries +8. Body cells use tiles BODY_TILE0 + 2k (VRAM bank 1), flash cells FLASH_TILE0 + 2k (bank 0).
VIEW_X0, VIEW_W = 16, 128
BODY_TILE0, FLASH_TILE0 = 224, 242

SX, SY = 1.0, 1.0       # native size, as on the A8 (scale() is a no-op copy at 1:1)

# (id, png) in WF_* order. Body frames first (<= 16 cells), then flashes (<= 7 cells).
BODY = [
    ("FIST_HAND", "fist_righthand_lines.png"),
    ("FIST_PUNCH", "fist_lefthand_lines.png"),
    ("SHOT", "shotgun_lines.png"),
    ("SHOT_COCK", "shotgun_cock_lines.png"),
    ("CHAIN_A", "chaingun_a_lines.png"),
    ("CHAIN_B", "chaingun_b_lines.png"),
    ("ROCKET", "rocketlauncher_lines.png"),
    ("PISTOL", "pistol_lines.png"),
    ("SAW", "chainsaw_lines.png"),
]
FLASH = [
    ("MUZZLE", "muzzle_flash.png"),
    ("MUZZLE_B", "muzzle_flash_b.png"),   # alternates with MUZZLE per shot
]


_SPRITES = None


def load_ink(name):
    """Ink bits for a sprite id (png-style name, e.g. "pistol_lines.png") from doom64.json."""
    global _SPRITES
    if _SPRITES is None:
        with open(DOC, encoding="utf-8") as f:
            _SPRITES = {sp["id"]: sp for sp in json.load(f).get("gbSprites", [])}
    sid = name[:-4] if name.endswith(".png") else name
    sp = _SPRITES.get(sid)
    if sp is None:
        raise SystemExit("gbc_genwpn: sprite %r missing from %s (gbSprites)" % (sid, DOC))
    return [[1 if c == "#" else 0 for c in row] for row in sp["rows"]]


def scale(bits):
    h, w = len(bits), len(bits[0])
    ow, oh = max(1, int(round(w * SX))), max(1, int(round(h * SY)))
    out = [[0] * ow for _ in range(oh)]
    for oy in range(oh):
        y0, y1 = oy / SY, (oy + 1) / SY
        for ox in range(ow):
            x0, x1 = ox / SX, (ox + 1) / SX
            tot = ink = 0.0
            yy = int(y0)
            while yy < y1 and yy < h:
                xx = int(x0)
                while xx < x1 and xx < w:
                    ov = (min(x1, xx + 1) - max(x0, xx)) * (min(y1, yy + 1) - max(y0, yy))
                    if ov > 0:
                        tot += ov
                        ink += ov * bits[yy][xx]
                    xx += 1
                yy += 1
            if tot and ink / tot >= 0.34:
                out[oy][ox] = 1
    return out


def cell_bytes(bits, cx, cy):
    """One 8x16 cell at pixel (cx, cy): 32 bytes (top tile then bottom tile), ink = colour 1."""
    h, w = len(bits), len(bits[0])
    out = []
    for ty in range(2):
        for r in range(8):
            y = cy + ty * 8 + r
            b = 0
            for x in range(8):
                xx = cx + x
                if 0 <= y < h and 0 <= xx < w and bits[y][xx]:
                    b |= 0x80 >> x
            out += [b, 0]
    return out


def frame_cells(bits):
    h, w = len(bits), len(bits[0])
    cells = []
    for cy in range(0, h, 16):
        for cx in range(0, w, 8):
            data = cell_bytes(bits, cx, cy)
            if any(data):
                cells.append((cx, cy, data))
    return w, h, cells


def main():
    outdir = sys.argv[1]
    os.makedirs(outdir, exist_ok=True)
    out = ["; Generated by tools/gbc_genwpn.py - do not edit."]
    ids = []
    frames = []
    for group, limit, tile0 in ((BODY, 16, BODY_TILE0), (FLASH, 7, FLASH_TILE0)):
        for name, png in group:
            bits = scale(load_ink(png))
            if group is BODY:
                # body art sits flush at the viewport bottom: drop blank rows under the ink
                while len(bits) > 1 and not any(bits[-1]):
                    bits.pop()
            w, h, cells = frame_cells(bits)
            assert len(cells) <= limit, (name, len(cells))
            frames.append((name, w, h, cells, tile0))
    for i, (name, w, h, cells, tile0) in enumerate(frames):
        ids.append(name)
        # tiles first, 16-byte aligned (GDMA source), then the placement list
        out.append('SECTION "wpn_%s", ROMX, BANK[%d], ALIGN[4]' % (name, WPN_BANK))
        out.append("WpnTiles%s:" % name)
        for (cx, cy, data) in cells:
            for k in range(0, 32, 16):
                out.append("    db " + ",".join(str(b) for b in data[k:k + 16]))
        out.append("WpnPlace%s:" % name)
        out.append("    db %d, %d, %d" % (len(cells), w, h))
        for k, (cx, cy, data) in enumerate(cells):
            x = VIEW_X0 + (VIEW_W - w) // 2 + cx + 8
            assert 0 < x < 256 and tile0 + 2 * k < 256
            out.append("    db %d, %d, %d" % (cy, x, tile0 + 2 * k))
    out.append('SECTION "wpn_index", ROM0')
    out.append("WpnBank:: db %d" % WPN_BANK)
    out.append("WpnFrameTab:: dw " + ",".join("WpnTiles%s, WpnPlace%s" % (n, n) for n in ids))
    open(os.path.join(outdir, "wpn.inc"), "w", newline="\n").write("\n".join(out) + "\n")
    with open(os.path.join(outdir, "wpn_ids.inc"), "w", newline="\n") as f:
        f.write("; Generated by tools/gbc_genwpn.py - do not edit.\n")
        for i, n in enumerate(ids):
            f.write("DEF WF_%s EQU %d\n" % (n, i))
        f.write("DEF WF_BODY_N EQU %d\n" % len(BODY))
    print("weapon frames:", ", ".join("%s %dx%d/%dc" % (n, w, h, len(c)) for (n, w, h, c, t) in frames))
    return frames


if __name__ == "__main__":
    main()
