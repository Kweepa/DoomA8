#!/usr/bin/env python3
"""Per-room collision records and the world test tables for the GBC build.

Writes <outdir>/worldrec.inc  (records, in each level's ROM bank, plus LevelCollTab in ROM0)
       <outdir>/worldtest.inc (test scenarios + walk script; only included by WORLDTEST builds)
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import gbc_genmap as gmap  # noqa: E402
import gbc_world as gw  # noqa: E402


def db(vals, per=16):
    return "\n".join("    db " + ",".join(str(v & 255) for v in vals[i:i + per]) for i in range(0, len(vals), per))


def main():
    outdir = sys.argv[1]
    os.makedirs(outdir, exist_ok=True)
    out = ["; Generated by tools/gbc_genworld.py - do not edit."]
    li = 0
    keys = []
    for key in gmap.gm.LEVEL_NAMES:
        lv = gmap.gm.load_level(key)
        if not any(o.get("kind") == "spawn" for o in (lv.get("objects") or [])):
            continue
        L = gw.Level(gmap.gm.cook_one(lv, key))
        out.append('SECTION "coll_%s", ROMX, BANK[%d]' % (key, gmap.FIRST_MAP_BANK + li))
        out.append("Map%s_CollTab::" % key)
        out.append("    dw " + ",".join("Map%s_Coll%d" % (key, r) for r in range(L.nrooms)))
        for r in range(L.nrooms):
            out.append("Map%s_Coll%d:" % (key, r))
            out.append(db(gw.room_record(L, r)))
        keys.append(key)
        li += 1
    out.append('SECTION "coll_index", ROM0')
    out.append("LevelCollTab:: dw " + ",".join("Map%s_CollTab" % k for k in keys))
    open(os.path.join(outdir, "worldrec.inc"), "w", newline="\n").write("\n".join(out) + "\n")

    tests = gw.world_tests()
    a, b = gw.wslice()
    tests = tests[a:b]
    script = gw.walk_script()
    t = ["; Generated by tools/gbc_genworld.py - do not edit.",
         "DEF NumWorldTests EQU %d" % len(tests), "EXPORT NumWorldTests",
         "DEF NumWalkSteps EQU %d" % len(script), "EXPORT NumWalkSteps",
         "WalkScript::"]
    for (joy, dt) in script:
        t.append("    db %d, %d" % (joy, dt))
    t.append("WorldTestTab::")
    for (lv_, room, cx, cz, cy, yaw, fy) in tests:
        t.append("    db %d, %d\n    dw %d, %d, %d\n    db %d, %d" % (lv_, room, cx, cz, cy, yaw, fy))
    open(os.path.join(outdir, "worldtest.inc"), "w", newline="\n").write("\n".join(t) + "\n")
    print("world records: %d levels, %d tests (slice %d:%d of %d), record %d B" % (len(keys), len(tests), a, b, len(gw.world_tests()), gw.ROOM_REC_LEN))


if __name__ == "__main__":
    main()
